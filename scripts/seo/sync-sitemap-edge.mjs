#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');
const SITEMAP_PATH = path.join(ROOT, 'public', 'sitemap.xml');
const OUTPUT_PATH = path.join(
  ROOT,
  'supabase',
  'functions',
  'sitemap-xml',
  'sitemap.generated.ts',
);

const sitemap = await fs.readFile(SITEMAP_PATH, 'utf8');
if (!sitemap.startsWith('<?xml') || !sitemap.includes('<urlset')) {
  throw new Error('public/sitemap.xml is not a valid sitemap payload');
}

const output = `// AUTO-GENERATED by scripts/seo/sync-sitemap-edge.mjs. Do not edit manually.
// Source of truth: public/sitemap.xml.
export const SITEMAP_XML = ${JSON.stringify(sitemap)};
`;

await fs.writeFile(OUTPUT_PATH, output, 'utf8');
console.log('[seo:sync-sitemap-edge] Synced public/sitemap.xml to Edge Function payload.');
