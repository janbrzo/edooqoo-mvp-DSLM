#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getContentRegistry, getRoutingDecisions } from './content-registry.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');
const OUTPUT = path.join(ROOT, 'cloudflare', 'content-routing.generated.mjs');
const PUBLIC_REDIRECTS_OUTPUT = path.join(ROOT, 'public', '_redirects');
const PUBLIC_HEADERS_OUTPUT = path.join(ROOT, 'public', '_headers');
const entries = getContentRegistry({ root: ROOT });
const decisions = getRoutingDecisions({ root: ROOT });
const publicRoutes = entries.filter((entry) => entry.indexable).map((entry) => entry.route);

const hostCanonicalRedirects = [
  'http://edooqoo.com/* https://edooqoo.com/:splat 301',
  'http://www.edooqoo.com/* https://edooqoo.com/:splat 301',
  'https://www.edooqoo.com/* https://edooqoo.com/:splat 301',
];

const routeRedirects = Object.entries(decisions.redirects)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([from, to]) => `${from} ${to} 301`);

const publicRedirects = [
  '# AUTO-GENERATED by scripts/seo/generate-edge-routing.mjs. Do not edit.',
  '# Cloudflare Pages-compatible fallback for canonical host and legacy content redirects.',
  ...hostCanonicalRedirects,
  ...routeRedirects,
  '',
].join('\n');

const noindexHeaders = decisions.noindex
  .filter((route) => route !== '/signup')
  .sort((a, b) => a.localeCompare(b))
  .flatMap((route) => [
    route,
    '  X-Robots-Tag: noindex, follow',
  ]);

const publicHeaders = [
  '# AUTO-GENERATED by scripts/seo/generate-edge-routing.mjs. Do not edit.',
  '# Cloudflare Pages-compatible fallback for public noindex routes when the Worker is not active.',
  '/signup',
  '  X-Robots-Tag: noindex, nofollow',
  '/signup/*',
  '  X-Robots-Tag: noindex, nofollow',
  ...noindexHeaders,
  '',
].join('\n');

const output = `// AUTO-GENERATED by scripts/seo/generate-edge-routing.mjs. Do not edit.
export const PUBLIC_ROUTES = new Set(${JSON.stringify(publicRoutes, null, 2)});
export const REDIRECTS = ${JSON.stringify(decisions.redirects, null, 2)};
export const GONE_ROUTES = new Set(${JSON.stringify(decisions.gone, null, 2)});
export const NOINDEX_ROUTES = new Set(${JSON.stringify(decisions.noindex, null, 2)});
`;

await fs.mkdir(path.dirname(OUTPUT), { recursive: true });
await fs.writeFile(OUTPUT, output, 'utf8');
await fs.writeFile(PUBLIC_REDIRECTS_OUTPUT, publicRedirects, 'utf8');
await fs.writeFile(PUBLIC_HEADERS_OUTPUT, publicHeaders, 'utf8');
console.log(`[edge-routing] Wrote ${publicRoutes.length} public routes to ${path.relative(ROOT, OUTPUT)}`);
console.log(`[edge-routing] Wrote ${routeRedirects.length + hostCanonicalRedirects.length} fallback redirects to ${path.relative(ROOT, PUBLIC_REDIRECTS_OUTPUT)}`);
console.log(`[edge-routing] Wrote ${decisions.noindex.length + 2} fallback noindex header rules to ${path.relative(ROOT, PUBLIC_HEADERS_OUTPUT)}`);

