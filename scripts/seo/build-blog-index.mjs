import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { basename, join } from 'path';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getContentRegistry, inferCluster } from './content-registry.mjs';

const BLOG_DIR = 'public/blog';
const TOP_DIR = 'public';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');
const CANONICAL_ALIASES = new Set([
  'exercise-types.html',
  'glossary.html',
  'how-it-works.html',
  'resources.html',
]);
const EXCLUDED_SITEMAP_PATHS = new Set([
  '/book',
  '/demo',
  '/login',
  '/signup',
  ...[...CANONICAL_ALIASES].map((slug) => `/${slug}`),
]);

function parseHtml(filepath, slugBase) {
  const html = readFileSync(filepath, 'utf8');
  const title = (html.match(/<title>([^<]+)<\/title>/i)?.[1] || '').replace(/\s+—\s+Edooqoo.*$/i, '').trim();
  const desc = (html.match(/<meta\s+name="description"\s+content="([^"]+)"/i)?.[1] || '').trim();
  const date = (html.match(/"datePublished"\s*:\s*"([^"]+)"/)?.[1] || '').trim();
  const slug = basename(filepath);
  return { title, description: desc, url: slugBase + '/' + slug, date };
}

const registry = getContentRegistry({ root: ROOT });
const registryByRoute = new Map(registry.map((entry) => [entry.route, entry]));

const blogFiles = readdirSync(BLOG_DIR)
  .filter(f => f.endsWith('.html') && f !== 'index.html')
  .map(f => join(BLOG_DIR, f));

const posts = blogFiles.map(fp => {
  const p = parseHtml(fp, '/blog');
  const entry = registryByRoute.get(p.url);
  return {
    ...p,
    category: entry?.cluster || inferCluster(`${p.url} ${p.title}`),
    state: entry?.state || 'hold',
  };
}).filter(p => p.title && p.description && registryByRoute.get(p.url)?.indexable !== false)
  .sort((a, b) => (b.date || '').localeCompare(a.date || ''));

console.log(`Parsed ${posts.length} blog posts`);

// Also top-level html
const topFiles = readdirSync(TOP_DIR)
  .filter(f =>
    f.endsWith('.html') &&
    f !== 'blog.html' &&
    f !== 'about.html' &&
    !CANONICAL_ALIASES.has(f)
  )
  .map(f => join(TOP_DIR, f));

const landings = topFiles.map(fp => {
  const html = readFileSync(fp, 'utf8');
  const title = (html.match(/<title>([^<]+)<\/title>/i)?.[1] || '').replace(/\s+\|\s+Edooqoo.*$/i, '').replace(/\s+—\s+Edooqoo.*$/i, '').trim();
  const desc = (html.match(/<meta\s+name="description"\s+content="([^"]+)"/i)?.[1] || '').trim();
  const slug = basename(fp);
  const url = '/' + slug;
  return { title, description: desc, url, state: registryByRoute.get(url)?.state || 'hold' };
}).filter(p => p.title && registryByRoute.get(p.url)?.indexable !== false);

console.log(`Parsed ${landings.length} top-level landings`);

const tsOut = `// AUTO-GENERATED by scripts/seo/build-blog-index.mjs — do not edit by hand.
// Source of truth: public/blog/*.html and public/*.html (v6.9.22).

export interface BlogPostMeta {
  title: string;
  description: string;
  url: string;
  date: string;
  category: string;
  state: 'keep' | 'improve' | 'hold';
}

export interface LandingPageMeta {
  title: string;
  description: string;
  url: string;
  state: 'keep' | 'improve' | 'hold';
}

export const BLOG_POSTS: BlogPostMeta[] = ${JSON.stringify(posts, null, 2)};

export const LANDING_PAGES: LandingPageMeta[] = ${JSON.stringify(landings, null, 2)};

export const BLOG_CATEGORIES = Array.from(new Set(BLOG_POSTS.map(p => p.category)));
`;

writeFileSync('src/data/blogIndex.ts', tsOut);
console.log('Wrote src/data/blogIndex.ts');

// ---- Sitemap extension ----
const sitemapPath = 'public/sitemap.xml';
let sitemap = readFileSync(sitemapPath, 'utf8');

// Strip any prior html entries (idempotent). This catches both old single-line
// entries and accidental Windows-path entries produced by older script runs.
sitemap = sitemap.replace(/\s*<url>\s*<loc>https:\/\/edooqoo\.com\/[^<]*\.html<\/loc>[\s\S]*?<\/url>\s*/g, '\n');
for (const route of EXCLUDED_SITEMAP_PATHS) {
  const escaped = route.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  sitemap = sitemap.replace(
    new RegExp(`\\s*<url>\\s*<loc>https:\\/\\/edooqoo\\.com${escaped}<\\/loc>[\\s\\S]*?<\\/url>\\s*`, 'g'),
    '\n',
  );
}

const htmlEntries = [
  ...posts.map(p => `  <url><loc>https://edooqoo.com${p.url}</loc>${p.date ? `<lastmod>${p.date}</lastmod>` : ''}<changefreq>monthly</changefreq><priority>0.7</priority></url>`),
  ...landings.map(l => `  <url><loc>https://edooqoo.com${l.url}</loc><changefreq>monthly</changefreq><priority>0.7</priority></url>`),
].join('\n');

sitemap = sitemap.replace('</urlset>', htmlEntries + '\n</urlset>');
writeFileSync(sitemapPath, sitemap);
console.log(`Sitemap updated: +${posts.length + landings.length} html URLs`);
