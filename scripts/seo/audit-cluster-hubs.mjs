#!/usr/bin/env node
/**
 * Sprint 3 — CI guard for the four topical cluster hubs.
 *
 * Verifies, without a browser:
 * 1. every hub route is registered in CORE_SEO_ROUTES (so it gets prerendered + sitemapped);
 * 2. every hub route has a React route in src/App.tsx;
 * 3. every hub has a citation block and a spoke list in src/constants/clusterHubs.ts;
 * 4. every declared HTML spoke exists and carries the hub backlink;
 * 5. hub SEO title <= 60 chars and description <= 155 chars.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CLUSTER_HUBS, CLUSTER_HUB_BACKLINK_MARKER } from './cluster-hubs.mjs';
import { CORE_SEO_ROUTES } from './seo-route-manifest.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');
const failures = [];
const passed = [];

const appTsx = fs.readFileSync(path.join(ROOT, 'src', 'App.tsx'), 'utf8');
const hubData = fs.readFileSync(path.join(ROOT, 'src', 'constants', 'clusterHubs.ts'), 'utf8');
const hubComponent = fs.readFileSync(
  path.join(ROOT, 'src', 'components', 'seo', 'ClusterHubPage.tsx'),
  'utf8',
);

if (!hubComponent.includes('data-citation-block')) {
  failures.push('ClusterHubPage.tsx no longer renders a data-citation-block element');
} else {
  passed.push('ClusterHubPage renders GEO citation block');
}

for (const hub of CLUSTER_HUBS) {
  const label = `[${hub.id}]`;

  if (!CORE_SEO_ROUTES.includes(hub.route)) {
    failures.push(`${label} ${hub.route} missing from CORE_SEO_ROUTES`);
  } else {
    passed.push(`${label} route registered for prerender`);
  }

  if (!appTsx.includes(`path="${hub.route}"`)) {
    failures.push(`${label} no React route for ${hub.route} in src/App.tsx`);
  } else {
    passed.push(`${label} React route present`);
  }

  if (!hubData.includes(`route: '${hub.route}'`)) {
    failures.push(`${label} clusterHubs.ts has no entry for ${hub.route}`);
  } else {
    passed.push(`${label} content entry present`);
  }

  if (hub.title.length > 60) failures.push(`${label} title ${hub.title.length} chars (>60)`);
  else passed.push(`${label} title length ok`);

  if (hub.description.length > 155) {
    failures.push(`${label} description ${hub.description.length} chars (>155)`);
  } else {
    passed.push(`${label} description length ok`);
  }

  for (const spoke of hub.htmlSpokes) {
    const file = path.join(ROOT, 'public', spoke);
    if (!fs.existsSync(file)) {
      failures.push(`${label} missing spoke file public/${spoke}`);
      continue;
    }
    const html = fs.readFileSync(file, 'utf8');
    if (!html.includes(`${CLUSTER_HUB_BACKLINK_MARKER}="${hub.id}"`) || !html.includes(`href="${hub.route}"`)) {
      failures.push(`${label} public/${spoke} is missing the hub backlink`);
    } else {
      passed.push(`${label} backlink ok: ${spoke}`);
    }
  }

  for (const spoke of hub.routeSpokes) {
    if (!appTsx.includes(`path="${spoke}"`)) {
      failures.push(`${label} routeSpoke ${spoke} has no React route`);
    } else {
      passed.push(`${label} routeSpoke ok: ${spoke}`);
    }
  }
}

const outputLines = [
  '# Cluster Hub Audit',
  '',
  'Generated by `scripts/seo/audit-cluster-hubs.mjs`.',
  '',
  `- Passed checks: ${passed.length}`,
  `- Failures: ${failures.length}`,
  '',
  '## Failures',
  '',
  failures.length ? failures.map((item) => `- ${item}`).join('\n') : '- none',
  '',
  '## RAG Keywords',
  '',
  'cluster hub audit, hub and spoke SEO, CEFR assessment hub, pronunciation teaching hub, ESL exercise design hub, tutor operations hub, GEO citation block, internal link equity.',
  '',
].join('\n');

fs.writeFileSync(path.join(ROOT, 'docs', 'seo', 'cluster-hubs.generated.md'), outputLines, 'utf8');

console.log(`[cluster-hubs] ${passed.length} passed, ${failures.length} failed`);
for (const failure of failures) console.error(`[cluster-hubs] FAIL ${failure}`);
if (failures.length) process.exit(1);
